package com.smartrasoi.threading;

import com.smartrasoi.model.Ingredient;
import com.smartrasoi.service.InventoryService;
import java.util.List;

/**
 * Unit 3 Syllabus Topic: Multithreading - Creating Threads by Extending Thread Class.
 *
 * Demonstrates:
 * - Extending java.lang.Thread
 * - Overriding run() method
 * - Thread naming and thread priority (setPriority, getPriority)
 * - Thread state inspection (isAlive, getState)
 * - Controlled execution simulating intensive kitchen inventory audit computation
 */
public class ReportGeneratorThread extends Thread {

    private final InventoryService inventoryService;
    private String generatedReportSummary;
    private long executionDurationMs;

    public ReportGeneratorThread(InventoryService inventoryService) {
        super("Rasoi-Audit-Thread");
        this.inventoryService = inventoryService;
        this.generatedReportSummary = "";
        // Thread priority demonstration (Unit 3: Thread Priorities)
        this.setPriority(Thread.NORM_PRIORITY + 1); // priority 6
    }

    @Override
    public void run() {
        long startTime = System.currentTimeMillis();
        // System.out.println(String.format("[%s] Started report generation with priority %d",
        //         getName(), getPriority()));

        try {
            // Simulate batch report calculation workload
            List<Ingredient> lowStock = inventoryService.getLowStockIngredients();
            double totalValuation = inventoryService.calculateTotalInventoryValue();

            // Controlled sleep to simulate data processing and demonstrate TIMED_WAITING state
            Thread.sleep(120);

            StringBuilder sb = new StringBuilder();
            sb.append("=== SMART RASOI AUDIT REPORT ===\n");
            sb.append("Generated by: ").append(getName()).append("\n");
            sb.append("Total Inventory Valuation: ₹").append(String.format("%.2f", totalValuation)).append("\n");
            sb.append("Low Stock Items Count: ").append(lowStock.size()).append("\n");
            for (Ingredient item : lowStock) {
                sb.append("  - ALERT: ").append(item.getName())
                  .append(" (").append(item.getQuantity()).append(" ").append(item.getUnit()).append(")\n");
            }
            sb.append("Status: COMPLETED AUDIT SUCCESSFULLY\n");

            this.generatedReportSummary = sb.toString();
        } catch (InterruptedException e) {
            // Handle thread interruption
            this.generatedReportSummary = "Report generation was interrupted!";
            Thread.currentThread().interrupt(); // Restore interrupted status
        } finally {
            this.executionDurationMs = System.currentTimeMillis() - startTime;
        }
    }

    public String getGeneratedReportSummary() {
        return generatedReportSummary;
    }

    public long getExecutionDurationMs() {
        return executionDurationMs;
    }
}
